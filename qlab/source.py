"""Source loading: C# preprocessor resolution, parsing, classification, tokens.

Every function here is deterministic. Line numbers are always 1-based and
preserved by the preprocessor (inactive lines become empty lines).
"""
from __future__ import annotations

import os
import re
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path

import tree_sitter_c_sharp as tscs
from tree_sitter import Language, Parser

LANG = Language(tscs.language())

# Symbols defined for a net8.0 Release build (what `dotnet build -f net8.0` defines).
DEFAULT_SYMBOLS = frozenset({
    "NET", "NET8_0", "NETCOREAPP", "RELEASE", "TRACE",
    "NET5_0_OR_GREATER", "NET6_0_OR_GREATER", "NET7_0_OR_GREATER", "NET8_0_OR_GREATER",
    "NETCOREAPP2_0_OR_GREATER", "NETCOREAPP2_1_OR_GREATER",
    "NETCOREAPP3_0_OR_GREATER", "NETCOREAPP3_1_OR_GREATER",
    "NETSTANDARD2_0_OR_GREATER", "NETSTANDARD2_1_OR_GREATER",
})

LITERAL_TYPES = frozenset({
    "integer_literal", "real_literal", "string_literal", "verbatim_string_literal",
    "raw_string_literal", "character_literal", "interpolated_string_expression",
    "utf8_string_literal",
})
KEEP_LITERALS = frozenset({"boolean_literal", "null_literal"})
SKIP_FOR_TOKENS = frozenset({"using_directive", "attribute_list", "extern_alias_directive",
                             "global_attribute", "comment"})

_PP = re.compile(r"^\s*#\s*(if|elif|else|endif)\b(.*)$")
_TOK = re.compile(r"\s*(&&|\|\||==|!=|!|\(|\)|[A-Za-z_][A-Za-z0-9_]*)")


def _eval_pp(expr: str, symbols: frozenset[str]) -> bool:
    expr = expr.split("//")[0].strip()
    out, pos = [], 0
    while pos < len(expr):
        m = _TOK.match(expr, pos)
        if not m:
            break
        tok = m.group(1)
        pos = m.end()
        if tok == "&&": out.append(" and ")
        elif tok == "||": out.append(" or ")
        elif tok == "!": out.append(" not ")
        elif tok in ("==", "!=", "(", ")"): out.append(f" {tok} ")
        elif tok == "true": out.append(" True ")
        elif tok == "false": out.append(" False ")
        else: out.append(" True " if tok in symbols else " False ")
    try:
        return bool(eval("".join(out) or "False", {"__builtins__": {}}, {}))
    except Exception:
        return False


def preprocess(text: str, symbols: frozenset[str] = DEFAULT_SYMBOLS) -> str:
    """Resolve #if/#elif/#else/#endif. Inactive and directive lines become ''."""
    lines = text.split("\n")
    out = []
    # stack entries: [parent_active, taken, active]
    stack: list[list[bool]] = []
    active = True
    for ln in lines:
        m = _PP.match(ln)
        if m:
            kw, rest = m.group(1), m.group(2)
            if kw == "if":
                cond = _eval_pp(rest, symbols)
                stack.append([active, cond, active and cond])
            elif kw == "elif" and stack:
                parent, taken, _ = stack[-1]
                cond = (not taken) and _eval_pp(rest, symbols)
                stack[-1] = [parent, taken or cond, parent and cond]
            elif kw == "else" and stack:
                parent, taken, _ = stack[-1]
                stack[-1] = [parent, True, parent and not taken]
            elif kw == "endif" and stack:
                stack.pop()
            active = stack[-1][2] if stack else True
            out.append("")
            continue
        out.append(ln if active else "")
    return "\n".join(out)


@dataclass
class SourceFile:
    path: str              # repo-relative, forward slashes
    text: str              # preprocessed text (same line count as raw)
    raw: str
    kind: str              # prod | test | generated | aux
    tree: object = None
    code_lines: set = field(default_factory=set)
    comment_lines: set = field(default_factory=set)
    tokens: list = field(default_factory=list)   # (norm, exact, line)
    masked_lines: set = field(default_factory=set)  # lines blanked by error containment

    @property
    def root(self):
        return self.tree.root_node

    @property
    def lines(self):
        return self.raw.split("\n")


GEN_NAME = re.compile(r"(\.g|\.generated|\.Designer|\.AssemblyInfo)\.cs$", re.I)


def classify(rel: str, raw: str, repo: Path) -> str:
    p = rel.replace("\\", "/")
    head = "\n".join(raw.split("\n")[:25])
    if GEN_NAME.search(p) or "<auto-generated" in head or "<autogenerated" in head:
        return "generated"
    tt = (repo / p).with_suffix(".tt")
    if tt.exists():
        return "generated"
    segs = p.split("/")
    if any(s.lower() in ("tests", "test") or s.endswith(".Tests") or s.endswith("Tests")
           or s.endswith(".Test") for s in segs[:-1]):
        return "test"
    if segs[0].lower() in ("sandbox", "benchmark", "benchmarks", "samples", "sample", "tools", "examples"):
        return "aux"
    return "prod"


@lru_cache(maxsize=1)
def parser() -> Parser:
    return Parser(LANG)


def _walk_tokens(node, out_tokens, code_lines, comment_lines, skip=False):
    t = node.type
    if t == "comment":
        for ln in range(node.start_point[0] + 1, node.end_point[0] + 2):
            comment_lines.add(ln)
        return
    if t.startswith("preproc"):
        return
    if t in LITERAL_TYPES or node.child_count == 0:
        if node.end_byte == node.start_byte:   # MISSING node
            return
        for ln in range(node.start_point[0] + 1, node.end_point[0] + 2):
            code_lines.add(ln)
        if skip:
            return
        exact = node.text.decode("utf8", "replace")
        if t in LITERAL_TYPES:
            norm = "LIT"
        elif t == "identifier":
            norm = "ID"
        else:
            norm = exact if not node.is_named or t in KEEP_LITERALS else exact
        out_tokens.append((norm, exact, node.start_point[0] + 1))
        return
    child_skip = skip or t in SKIP_FOR_TOKENS
    if t in ("namespace_declaration", "file_scoped_namespace_declaration"):
        for c in node.children:
            if c.type in ("qualified_name", "identifier") and c == node.child_by_field_name("name"):
                _walk_tokens(c, out_tokens, code_lines, comment_lines, True)
            else:
                _walk_tokens(c, out_tokens, code_lines, comment_lines, child_skip)
        return
    for c in node.children:
        _walk_tokens(c, out_tokens, code_lines, comment_lines, child_skip)


# tree-sitter-c-sharp 0.23 cannot parse pointer indirection of a parenthesised
# operand, e.g. `*(int*)(p + 0) = v;`. We rewrite a *prefix* `*(` to `+(`, which
# keeps line numbers, the operand structure and all complexity-relevant tokens.
_DEREF = re.compile(r"((?:^|[(=,;{}\[?:!&|+\-*/<>%^~])\s*|\breturn\s+|\bcase\s+)\*(?=\s*\()", re.M)


def _rewrite_grammar_gaps(text: str) -> str:
    prev = None
    while prev != text:
        prev = text
        text = _DEREF.sub(lambda m: m.group(1) + "+", text)
    return text


def _balanced(chunk: str) -> bool:
    return (chunk.count("(") == chunk.count(")") and chunk.count("{") == chunk.count("}")
            and chunk.count("[") == chunk.count("]"))


def _innermost_error_lines(root) -> list[int]:
    out, st = set(), [root]
    while st:
        n = st.pop()
        if n.is_missing:
            out.add(n.start_point[0])
        if n.type == "ERROR" and not any(c.type == "ERROR" for c in n.children):
            out.add(n.start_point[0])
        st.extend(n.children)
    return sorted(out)


def _mask_errors(text: str, max_iter: int = 40):
    """Statement-level error containment: blank the smallest balanced statement
    window around each innermost parse error. Returns (text, tree, masked_lines)."""
    masked: set[int] = set()
    tree = parser().parse(text.encode("utf8"))
    for _ in range(max_iter):
        if not tree.root_node.has_error:
            break
        lines = text.split("\n")
        changed = False
        for L in _innermost_error_lines(tree.root_node):
            if L in masked or L >= len(lines):
                continue
            a = L
            while a > 0 and not lines[a - 1].rstrip().endswith((";", "{", "}")) and L - a < 12:
                a -= 1
            b = L
            while b < len(lines) - 1 and not (lines[b].rstrip().endswith(";") and _balanced("\n".join(lines[a:b + 1]))) and b - L < 12:
                b += 1
            chunk = "\n".join(lines[a:b + 1])
            if not lines[b].rstrip().endswith(";") or not _balanced(chunk):
                continue
            for k in range(a, b + 1):
                if lines[k].strip():
                    # first line keeps an empty statement so `case X:` sections stay valid
                    lines[k] = " " * (len(lines[k]) - 1) + (";" if k == a else " ")
                    masked.add(k)
            changed = True
            break   # re-parse after each window: one fix can remove many errors
        if not changed:
            break
        text = "\n".join(lines)
        tree = parser().parse(text.encode("utf8"))
    return text, tree, {m + 1 for m in masked}


def load_file(repo: Path, rel: str, symbols=DEFAULT_SYMBOLS, text: str | None = None) -> SourceFile:
    raw = text if text is not None else (repo / rel).read_text(encoding="utf-8-sig", errors="replace")
    raw = raw.replace("\r\n", "\n")
    pre = _rewrite_grammar_gaps(preprocess(raw, symbols))
    pre, tree, masked = _mask_errors(pre)
    sf = SourceFile(path=rel.replace("\\", "/"), text=pre, raw=raw, kind=classify(rel, raw, repo))
    sf.tree = tree
    sf.masked_lines = masked
    _walk_tokens(sf.tree.root_node, sf.tokens, sf.code_lines, sf.comment_lines)
    sf.code_lines |= masked
    return sf


EXCLUDE_DIRS = {"obj", "bin", ".git", "node_modules", "packages", ".vs"}


def list_cs_files(repo: Path) -> list[str]:
    out = []
    for dirpath, dirnames, filenames in os.walk(repo):
        dirnames[:] = [d for d in dirnames if d not in EXCLUDE_DIRS and not d.startswith(".")]
        for fn in filenames:
            if fn.endswith(".cs"):
                out.append(os.path.relpath(os.path.join(dirpath, fn), repo).replace("\\", "/"))
    return sorted(out)


def load_repo(repo: Path, kinds=None, symbols=DEFAULT_SYMBOLS, include=None) -> list[SourceFile]:
    files = []
    for rel in list_cs_files(repo):
        if include and not any(rel.startswith(i) for i in include):
            continue
        sf = load_file(repo, rel, symbols)
        if kinds is None or sf.kind in kinds:
            files.append(sf)
    return files


def error_fraction(sf: SourceFile) -> float:
    total = max(1, len(sf.text.encode("utf8")))
    eb = 0
    st = [sf.root]
    while st:
        n = st.pop()
        if n.type == "ERROR":
            eb += n.end_byte - n.start_byte
            continue
        st.extend(n.children)
    return eb / total
